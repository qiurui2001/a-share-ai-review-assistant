# -*- coding: utf-8 -*-
"""
tasks.py —— 串行任务链
========================

数据流：researcher_task → fact_check_task → review_task → analyzer_task → writer_task → deliver_task

约定：main.py 以 inputs={"today": "YYYY-MM-DD"} 启动，任务里的 {today} 会被自动替换。
"""

from __future__ import annotations

from crewai import Task

from agents import analyzer, fact_checker, paper_trader, researcher, review_validator, writer

# ══════════════════════════════════════════════════════════════════════════════
# 任务 1：信息收集
# ══════════════════════════════════════════════════════════════════════════════
researcher_task = Task(
    description=(
        "今天是 {today}。请完成当日 A 股盘后信息收集，务必调用工具拿到**真实数据**，不要凭记忆编写。\n\n"
        "收集范围（按优先级）：\n"
        "1. 大盘：调用「get_market_overview」拿到各大指数收盘点位、涨跌幅、两市成交额。\n"
        "2. 量价结构：调用「get_index_kline」查看上证指数、创业板指近 60 根日 K，"
        "记录均线位置、近 20 日高低点、近 5 日量能变化。\n"
        "3. 板块：分别调用「get_sector_flow」（industry 与 concept，top_n=5），"
        "工具会以 **Markdown 表格** 返回涨幅/跌幅/主力净流入/主力净流出四个榜单，请原样保留表格。\n"
        "4. 市场宽度：调用「get_market_breadth」，记录上涨/下跌/涨停/跌停家数。\n"
        "5. 短线情绪：调用「get_limit_pool」，记录最高板、连板梯队、炸板率、跌停家数。\n"
        "6. 消息面：调用「get_market_news」拿最新要闻；再用「web_search」检索"
        "「A股 {today} 复盘 大盘 原因」，必要时用「fetch_webpage」深读重点文章。\n"
        "7. 外围：调用「get_global_markets」，记录隔夜美股、港股、美元指数表现。\n\n"
        "输出要求：分「大盘 / 板块资金 / 市场宽度与情绪 / 消息面 / 国际形势」五节，"
        "每条信息必须带具体数字、时间与来源，并标注它是利好、利空还是中性。"
        "不要写分析结论，只做客观汇总。"
    ),
    expected_output=(
        "一份结构化的原始情报 MARKDOWN，包含：\n"
        "- 大盘：各指数收盘价与涨跌幅、两市成交额\n"
        "- 板块资金：行业/概念涨幅榜、跌幅榜、主力净流入/流出榜\n"
        "- 市场宽度与情绪：涨跌家数、涨停/跌停家数、最高连板、炸板率\n"
        "- 消息面：当日重要利好利空（含来源）\n"
        "- 国际形势：隔夜外盘与宏观事件\n"
        "全部为带数字的事实，不含主观判断。"
    ),
    agent=researcher,
    output_file="outputs/01_research_{today}.md",
)

# ══════════════════════════════════════════════════════════════════════════════
# 任务 2：事实核查（只审研究员，防止幻觉）
# ══════════════════════════════════════════════════════════════════════════════
fact_check_task = Task(
    description=(
        "只看上一步【研究员】的原始情报，对它做独立的事实核查，目的是**减少幻觉**。"
        "你不需要做任何行情分析或预测。\n\n"
        "核查方法（必须亲自调用工具，不能凭记忆判断）：\n"
        "1. 指数点位/涨跌幅/成交额 → 用 get_market_overview 重新取数，逐项比对。\n"
        "2. 均线、区间高低点、量能表述 → 用 get_index_kline 复核。\n"
        "3. 板块涨跌与主力资金 → 用 get_sector_flow(industry) 与 get_sector_flow(concept) 抽查。\n"
        "4. 涨跌家数、涨停/跌停、连板、炸板率 → 用 get_market_breadth、get_limit_pool 复核。\n"
        "5. 消息面/外围 → 用 get_market_news、get_global_markets 抽查，并注意研究员是否"
        "把「时间窗」当成「具体事件」来写。\n\n"
        "对每一项给出判定：✅一致 / ❌错误（附工具值与研究员值）/ ⚠️无法核验（工具取不到）。\n"
        "严禁替研究员补写、猜测或美化；严禁输出任何预测性结论。\n\n"
        "最后输出「修正后的情报」：保留✅与⚠️的原始内容，把❌的错误数据替换为工具值并标注，"
        "供下游分析师直接使用。"
    ),
    expected_output=(
        "一份事实核查报告 MARKDOWN，包含：\n"
        "- 核对结论（通过率、发现的问题数量与严重度）\n"
        "- 差异清单（逐项：项目 / 研究员值 / 工具值 / 判定 / 说明）\n"
        "- 无法核验项清单\n"
        "- 修正后的完整情报（错误已更正并标注，不含预测）"
    ),
    agent=fact_checker,
    context=[researcher_task],
    output_file="outputs/01b_factcheck_{today}.md",
)

# ══════════════════════════════════════════════════════════════════════════════
# 任务 3：往期预测验证（RAG 回溯，闭环校准）
# ══════════════════════════════════════════════════════════════════════════════
review_task = Task(
    description=(
        "今天是 {today}。请对【往期复盘报告里做出的预测】做一次回溯验证，形成『预测 → 实际 → 归因』的闭环。\n\n"
        "步骤（必须调用工具，不能凭记忆）：\n"
        "1. 用 retrieve_past_predictions 检索往期预测：\n"
        "   - query 建议：「下一交易日及未来1-2周 走势预判 情景 概率 支撑位 压力位 操作策略 仓位」；\n"
        "   - top_k=8、days_back=30、exclude_date=\"{today}\"（排除本次正在生成的报告）。\n"
        "2. 重点核对两类预测：\n"
        "   - 最近一份报告的『次日』预测 → 是否就是今天（或最近交易日）的走势；\n"
        "   - 更早报告（约 5-10 个交易日前）的『未来 1-2 周』预测 → 是否已被今天的走势验证或证伪。\n"
        "3. 用 get_market_overview / get_index_kline 取今日（最近交易日）的**真实**指数点位、涨跌幅、"
        "量能，与往期预测中的具体点位/情景/概率逐条比对。\n"
        "4. 每条给出：预测内容（含原报告日期与我方原文）/ 实际走势 / 结论（✅命中 / ⚠️部分命中 / ❌偏离 / "
        "无法验证）/ 偏差幅度 / 归因（是逻辑错、数据错，还是被突发消息扰动）。\n"
        "5. 最后给「校准结论」：本期分析应吸取的经验、需要修正的惯性误判。\n"
        "6. 调用 get_prediction_stats 取「全时段 + 近 5 份报告」的滚动命中率，作为验证概览的一部分。\n\n"
        "红线：只依据往期报告原文与工具真实数据；对不上就写偏离，取不到就写无法验证；**严禁编造往期预测**。"
        "若检索不到往期报告，如实说明『首次运行、无往期可验证』。"
    ),
    expected_output=(
        "一份《往期预测验证》MARKDOWN，包含：\n"
        "- 验证概览（检索到的往期报告、命中率统计、**滚动命中率**）\n"
        "- 逐条验证表（报告日期 / 预测内容 / 实际走势 / 结论 / 偏差 / 归因）\n"
        "- 校准结论（本期应吸取的经验与需修正的误判）\n"
        "无往期报告时，明确说明并可给出空表与说明。"
    ),
    agent=review_validator,
    context=[fact_check_task],
    output_file="outputs/01c_review_{today}.md",
)

# ══════════════════════════════════════════════════════════════════════════════
# 任务 4：盘面分析
# ══════════════════════════════════════════════════════════════════════════════
analyzer_task = Task(
    description=(
        "基于核查员给出的【修正后的情报】，对 {today} 的 A 股盘面做一次专业、有观点的深度分析。"
        "凡标注❌已修正的数据，以修正值为准；⚠️无法核验的数据不要引用或需注明。"
        "同时请参考【往期预测验证】的校准结论，主动规避此前重复出现的误判。\n\n"
        "分析框架（缺一不可）：\n"
        "1. 量价分析：结合指数点位、成交额与量能变化，判断是放量上攻、缩量调整还是放量杀跌，"
        "量价是否背离。\n"
        "2. 板块与资金：从领涨/领跌板块识别当日主线与退潮方向，分析资金是在抱团还是在扩散，"
        "判断主线有没有持续性。\n"
        "3. 技术分析：给出关键支撑位与压力位（要写具体点位），判断指数所处均线结构"
        "（多头/空头/纠缠），并用波浪理论粗略定位当前处于哪一浪或哪个阶段。\n"
        "4. 情绪周期：结合涨停家数、最高连板、炸板率，判断情绪处于冰点、修复、高潮还是退潮。\n"
        "5. 消息面与外围：评估当日消息和隔夜外盘对次日的边际影响。\n"
        "6. 预判与策略：给出对次日及未来 1-2 周的走势预判（分乐观/中性/悲观三种情景及各自概率），"
        "并给出对应的仓位与操作建议（波段视角，说明什么信号出现该加仓/减仓/止损）。\n\n"
        "要求：结论先行、逻辑支撑、敢下判断，但必须说明「什么情况会证伪」。"
        "如对数据仍有疑问，可调用工具再次核对。"
    ),
    expected_output=(
        "一份盘面分析 MARKDOWN，包含：\n"
        "- 量价与资金结论\n"
        "- 明确的支撑位、压力位点位\n"
        "- 波浪/结构定位\n"
        "- 情绪周期定位\n"
        "- 分情景的次日及短期走势预判（含概率）\n"
        "- 可执行的仓位与操作策略，以及证伪条件"
    ),
    agent=analyzer,
    context=[fact_check_task, review_task],
    output_file="outputs/02_analysis_{today}.md",
)

# ══════════════════════════════════════════════════════════════════════════════
# 任务 5：模拟交易（10 万模拟盘，收盘调仓，仅输出表格、不发邮件）
# ══════════════════════════════════════════════════════════════════════════════
paper_trade_task = Task(
    description=(
        "你是 10 万元模拟账户的交易员，请在 {today} 收盘做一次调仓。**只输出交易表格，不发任何邮件**。\n\n"
        "步骤：\n"
        "1. 先调用 paper_portfolio 查看当前现金、持仓与盈亏。\n"
        "2. 阅读上下文里的【盘面分析】与【往期预测验证】结论，确定今日主线与退潮方向。\n"
        "3. 用 get_quote 查询候选标的（个股或 ETF 的腾讯代码，如 sh510300 沪深300ETF、sh588000 科创50ETF、"
        "sh600519 等）的现价。\n"
        "4. 决策并执行：paper_buy(code, amount, reason) 买入、paper_sell(code, ratio, reason) 卖出。\n"
        "5. 最后调用 paper_report 生成报表（交易流水 / 当前持仓 / 账户汇总 / **净资产曲线与逐日收益**），"
        "并把返回内容**作为最终输出原样保留**（尤其不得删除其中的表格与 `![...](...)` 图片行）。\n\n"
        "交易纪律（务必遵守）：\n"
        "- 持仓 2–4 个标的；**单票不超过总资产 30%**；**总仓位不超过 80%**；\n"
        "- 优先跟随当日**强势主线**（ETF 或龙头个股），**回避**破位/退潮方向；\n"
        "- 止损：个股浮亏约 7–8% 或跌破分析给出的关键支撑 → 卖出；\n"
        "- 理由一句话（≤20 字）；无可操作机会时**空仓或维持**并说明。\n\n"
        "禁止：编造行情、满仓单票、无理由频繁交易。"
    ),
    expected_output=(
        "一份模拟交易报表 MARKDOWN：交易流水表（时间/代码/名称/方向/价格/数量/金额/仓位%/持有状态/盈亏/理由）"
        "+ 当前持仓表 + 账户汇总（初始资金、现金、持仓市值、总资产、收益率）。"
    ),
    agent=paper_trader,
    context=[analyzer_task, review_task],
    output_file="paper/交易_{today}.md",
)

# ══════════════════════════════════════════════════════════════════════════════
# 任务 6：撰写（含 K 线图）与交付
# ══════════════════════════════════════════════════════════════════════════════
writer_task = Task(
    description=(
        "把研究院的分析整理、润色成一份完整的 {today} A股复盘报告（正文即最终交付物，"
        "后续会有独立任务负责存档与发送，你这里只需把正文写好）。\n\n"
        "第一步（重要）：调用 generate_index_charts 生成大盘 K 线图（近三个月），"
        "它会返回若干行 Markdown 图片语法。\n\n"
        "报告结构：\n"
        "# A股复盘 | {today}\n"
        "## 一、今日大盘\n"
        "  1) 用一个 **Markdown 表格** 列出主要指数：指数 / 收盘 / 涨跌幅 / 近5日量能变化 / 量价定性。"
        "表格必须列数对齐、分隔行与表头列数一致（例如 5 列就写 5 个 |---|）。\n"
        "  2) 表格下方，把 generate_index_charts 返回的图片行 **原样插入**，作为大盘走势的直观展示。\n"
        "## 二、往期预测验证\n"
        "  先在开头写一行**滚动命中率统计**（采用校验员输出里的 get_prediction_stats 结果，"
        "如「全时段✅命中率 X%、宽松命中率 Y%；近5份 …」），再用 **Markdown 表格** 呈现："
        "报告日期 / 预测内容（含关键点位）/ 实际走势 / 结论（✅命中 / ⚠️部分命中 / ❌偏离）/ 偏差 / 归因；"
        "表后写 2-3 句校准结论。若往期无报告，写明「首次运行，暂无往期可验证」。\n"
        "## 三、板块与资金\n"
        "  **做法固定**：分别调用 get_sector_flow(board=\"industry\", top_n=5) 和 "
        "get_sector_flow(board=\"concept\", top_n=5)，把两次返回里的 8 张 Markdown 表格 "
        "**逐字原样粘贴**（不要改写、不要精简、不要把有数据的单元格写成「数据缺失」），"
        "然后在表格后写 2-3 句主线与退潮点评。\n"
        "## 四、技术与情绪（支撑压力位、浪型、情绪周期）\n"
        "## 五、消息面与外围\n"
        "## 六、后市预判与操作策略（含仓位建议与风险提示）\n\n"
        "写作要求：\n"
        "- 结论先行，语言专业但通俗，重点用 **加粗**。\n"
        "- 所有表格都必须是规范的 Markdown 表格，列数前后一致。\n"
        "- 保留所有关键数字和点位，不得杜撰数据；对缺失数据要如实说明。\n"
        "- 文末必须包含「风险提示」和不构成投资建议的免责声明。\n"
        "- 报告要完整收尾，不要写到一半中断。"
    ),
    expected_output=(
        "一份完整、可直接发送客户的A股复盘报告 MARKDOWN："
        "含规范的指数表格与指数 K 线图、往期预测验证表、六大章节、明确点位/数据、"
        "风险提示与免责声明，且已完整结尾。"
    ),
    agent=writer,
    context=[analyzer_task, review_task],
    output_file="outputs/03_report_{today}.md",
)

# ══════════════════════════════════════════════════════════════════════════════
# 任务 7：交付（独立成任务，确保一定调用发送工具）
# ══════════════════════════════════════════════════════════════════════════════
deliver_task = Task(
    description=(
        "上游任务已经产出完整的《A股复盘 | {today}》报告正文，并已保存为文件 "
        "outputs/03_report_{today}.md（见上下文）。你**只做交付**，不要重写报告、"
        "不要在最终回答里粘贴全文：\n\n"
        "1. 调用 save_report_file：source_file = outputs/03_report_{today}.md，"
        "filename = A股复盘_{today}.md，content = 上游报告的完整正文。\n"
        "2. 调用 send_email_report：subject = A股复盘 | {today} 大盘回顾与操作策略，"
        "**content 留空**，source_file = 上一步 save_report_file 返回的报告路径。\n"
        "3. 最终回答只需一句话，汇报「存档路径 + 邮件发送结果」。\n\n"
        "提示：优先用 source_file 传大段文本，避免把超长正文塞进工具参数导致解析失败。"
    ),
    expected_output="一句话交付结果：报告存档路径 + 邮件是否发送成功。",
    agent=writer,
    context=[writer_task],
    output_file="outputs/04_delivery_{today}.md",
)

TASKS = [researcher_task, fact_check_task, review_task, analyzer_task,
         paper_trade_task, writer_task, deliver_task]
